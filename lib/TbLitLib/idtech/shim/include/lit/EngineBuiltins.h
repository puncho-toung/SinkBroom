/**
 * A define of a builtin's permutation (shaderMacro_t). A null value is
 * usePushConstants( layout ) (RenderProgs.cpp:777): "1" when the row's binding layout
 * uses push constants on the device (lit/EngineTables.h enginePushConstantsEnabled), else
 * "0"; in the engine's table it always names the row's own binding layout.
 */
struct EngineBuiltinDefine
{
  const char* name = nullptr;
  const char* value = nullptr;
};

inline constexpr std::size_t EngineBuiltinMaxDefines = 7;

// RenderProgs.cpp:780-790 builtinShaders_t
struct EngineBuiltin
{
  // the BUILTIN_ index, which equals the row's place (RenderProgs.cpp:968, SC245)
  int index = 0;
  const char* name = nullptr;
  const char* nameOutSuffix = nullptr;
  std::array<EngineBuiltinDefine, EngineBuiltinMaxDefines> defines = {};
  std::size_t defineCount = 0;
  bool requireGPUSkinningSupport = false;
  int stages = 0;
  EngineVertexLayout vertexLayout = EngineVertexLayout::Unknown;
  EngineBindingLayout bindingLayout = EngineBindingLayout::Default;
};

